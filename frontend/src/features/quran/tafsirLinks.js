export function fiZilalLink(surah) {
  const entry = FI_ZILAL[surah - 1];
  return entry ? { url: FI_ZILAL_BASE + entry[0], sizeMb: entry[1] } : null;
}

// Tafsir Ibn Kathir (English) on alim.org has a page per ayat; ayat 0 is the
// surah's introduction.
export function ibnKathirUrl(surah, ayat = 0) {
  return `https://www.alim.org/quran/tafsir/ibn-kathir/surah/${surah}/${ayat}/`;
}
